using Fanex.ScoreBox.Business.Models;
using Fanex.Service.Core;
using OfficeOpenXml;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace Fanex.ScoreBox.Business.Services
{
    public interface ExcelService
    {
        string Execute(bool isDaily, IEnumerable<ScoreBoxModel> data);
    }

    public class ExcelServiceImp : ExcelService
    {
        private readonly ExcelPackage excelPackage;
        private readonly DateProvider dateProvider;
        private readonly ExcelWorksheet template;

        public ExcelServiceImp(ExcelPackage excelPackage, DateProvider dateProvider)
        {
            this.excelPackage = excelPackage;
            this.dateProvider = dateProvider;

            template = excelPackage.Workbook.Worksheets["Template"];
        }

        public string Execute(bool isDaily, IEnumerable<ScoreBoxModel> data)
        {
            RenderBody(data);
            var filepath = string.Empty;

            if (isDaily)
            {
                FormatDailyTitle(isDaily);
                filepath = SaveDailyFile(isDaily);
            }
            else
            {
                FormatMonthlyTitle(isDaily);
                filepath = SaveMonthlyFile(isDaily);
            }

            return filepath;
        }

        private void RenderBody(IEnumerable<ScoreBoxModel> data)
        {
            const int StartRowIndex = 13;
            const int StartColIndex = 2;
            const int TotalCol = 24;
            var maxRowIndex = data.Count() + 12;
            template.Cells["B13"].LoadFromCollection(data, false);

            for (int columnIndex = 0; columnIndex < TotalCol; columnIndex++)
            {
                template.Cells[StartRowIndex, StartColIndex + columnIndex, maxRowIndex, StartColIndex + columnIndex].StyleID = template.Cells[StartRowIndex, StartColIndex + columnIndex].StyleID;
            }
        }

        private void FormatDailyTitle(bool isDaily)
        {
            var date = dateProvider.Date(isDaily);
            template.Cells["B2"].Value = $"Daily Score Box Win Loss Report For {date.FromDate:yyyy/MM/dd}";
            template.Cells["B3"].Value = $"Generated by StarixIT on {SystemTime.Now:yyyy/MM/dd hh:mm:tt}";
            template.Cells["C8"].Value = $"{date.FromDate:yyyy/MM/dd}";
            template.Name = "Daily Score Box Win Loss";
        }

        private void FormatMonthlyTitle(bool isDaily)
        {
            var date = dateProvider.Date(isDaily);
            template.Cells["B2"].Value = $"Monthly Score Box Win Loss Report For {date.FromDate:yyyy/MM} ";
            template.Cells["B3"].Value = $"Generated by StarixIT on {SystemTime.Now:yyyy/MM/dd hh:mm:tt}";
            template.Cells["C8"].Value = $"{date.FromDate:yyyy/MM}";
            template.Name = "Monthly Score Box Win Loss";
        }

        private string SaveDailyFile(bool isDaily)
        {
            var date = dateProvider.Date(isDaily);
            var fileName = $"Daily_Score_Box_Win_Loss_For_{date.FromDate:yyyyMMdd}.xlsx";
            var path = $@"{AppConfigService.AppConfig.FilePath}\{SystemTime.Now:yyyy}\{SystemTime.Now:MM}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.AppConfig.Password);

            return path;
        }

        private string SaveMonthlyFile(bool isDaily)
        {
            var date = dateProvider.Date(isDaily);
            var fileName = $"Monthly_Score_Box_Win_Loss_For_{date.FromDate:yyyyMM}.xlsx";
            var path = $@"{AppConfigService.AppConfig.FilePath}\{SystemTime.Now:yyyy}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.AppConfig.Password);

            return path;
        }
    }
}