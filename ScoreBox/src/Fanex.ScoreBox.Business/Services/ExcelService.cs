using Fanex.ScoreBox.Business.Models;
using Fanex.Service.Core;
using OfficeOpenXml;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace Fanex.ScoreBox.Business.Services
{
    public interface ExcelService
    {
        string Execute(bool isDaily, IEnumerable<ScoreBoxModel> data);
    }

    public class ExcelServiceImp : ExcelService
    {
        private readonly ExcelPackage excelPackage;
        private readonly DateProvider dateProvider;
        private readonly ExcelWorksheet template;
        private readonly Dictionary<bool, Dictionary<int, string>> sheetNames;
        private DateService dateService;

        public ExcelServiceImp(ExcelPackage excelPackage, DateProvider dateProvider)
        {
            this.excelPackage = excelPackage;
            this.dateProvider = dateProvider;

            template = excelPackage.Workbook.Worksheets["Template"];
            excelPackage.Workbook.Worksheets.Delete(template);
            sheetNames = new Dictionary<bool, Dictionary<int, string>>
            {
                { true, new Dictionary<int, string>
                {
                    { 1, "DSB-Live" },
                    { 0, "DSB-Nonive" }
                }
                },

                { false, new Dictionary<int, string>
                {
                    { 1, "MSB-Live" },
                    { 0, "MSB-Nonlive" },
                }
                }
            };
        }

        public string Execute(bool isDaily, IEnumerable<ScoreBoxModel> data)
        {
            var filepath = string.Empty;
            dateService = dateProvider.Date(isDaily);
            data.GroupBy(g => g.LiveStatus)
                .ToList()
                .ForEach(dataByStatus => 
                {
                    var sheetName = GetSheetName(isDaily, dataByStatus.Key);
                    var sheet = excelPackage.Workbook.Worksheets.Add(sheetName);
                    RenderBody(sheet, dataByStatus);
                    if (isDaily)
                    {
                        FormatDailyTitle(sheet);
                        filepath = SaveDailyFile();
                    }
                    else
                    {
                        FormatMonthlyTitle(sheet);
                        filepath = SaveMonthlyFile();
                    }
                });

            return filepath;
        }

        private void RenderBody(ExcelWorksheet sheet, IEnumerable<ScoreBoxModel> data)
        {
            const int StartRowIndex = 13;
            const int StartColIndex = 2;
            const int TotalCol = 27;
            const int shiftColumn = 1;
            const int freezeColumn = 6;
            var maxRowIndex = data.Count() + 12;
            sheet.Cells["B13"].LoadFromCollection(data, false);

            for (int columnIndex = 0; columnIndex < TotalCol; columnIndex++)
            {
                template.Cells[StartRowIndex - 1, StartColIndex, StartRowIndex - 1, TotalCol].Copy(sheet.Cells[StartRowIndex - 1, StartColIndex, StartRowIndex - 1, TotalCol]);
                sheet.Cells[StartRowIndex, StartColIndex + columnIndex, maxRowIndex, StartColIndex + columnIndex].StyleID = template.Cells[StartRowIndex, StartColIndex + columnIndex].StyleID;
                sheet.Column(columnIndex + 1).AutoFit();
            }

            sheet.Column(TotalCol + shiftColumn).Hidden = true;
            sheet.View.FreezePanes(StartRowIndex, freezeColumn);
        }

        private string GetSheetName(bool isDaily, int liveStatus)
        {
            return sheetNames[isDaily][liveStatus];            
        }

        private void FormatDailyTitle(ExcelWorksheet sheet)
        {
            template.Cells["B2:C10"].Copy(sheet.Cells["B2:C10"]);
            sheet.Cells["B2"].Value = $"Daily Score Box Win Loss Report For {dateService.FromDate:yyyy/MM/dd}";
            sheet.Cells["B3"].Value = $"Generated by StarixIT on {SystemTime.Now:yyyy/MM/dd hh:mm:tt}";
            sheet.Cells["C8"].Value = $"{dateService.FromDate:yyyy/MM/dd}";            
        }

        private void FormatMonthlyTitle(ExcelWorksheet sheet)
        {
            template.Cells["B2:C10"].Copy(sheet.Cells["B2:C10"]);
            sheet.Cells["B2"].Value = $"Monthly Score Box Win Loss Report For {dateService.FromDate:yyyy/MM} ";
            sheet.Cells["B3"].Value = $"Generated by StarixIT on {SystemTime.Now:yyyy/MM/dd hh:mm:tt}";
            sheet.Cells["C8"].Value = $"{dateService.FromDate:yyyy/MM}";            
        }

        private string SaveDailyFile()
        {            
            var fileName = $"Daily_Score_Box_Win_Loss_For_{dateService.FromDate:yyyyMMdd}.xlsx";
            var path = $@"{AppConfigService.AppConfig.FilePath}\{SystemTime.Now:yyyy}\{SystemTime.Now:MM}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.AppConfig.Password);

            return path;
        }

        private string SaveMonthlyFile()
        {            
            var fileName = $"Monthly_Score_Box_Win_Loss_For_{dateService.FromDate:yyyyMM}.xlsx";
            var path = $@"{AppConfigService.AppConfig.FilePath}\{SystemTime.Now:yyyy}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.AppConfig.Password);

            return path;
        }
    }
}