using System;
using System.IO;
using BettypeWith3rdProducts.Business.Services;
using BettypeWith3rdProducts.Business.Utility;
using NSubstitute;
using NUnit.Framework;

namespace BettypeWith3rdProducts.UnitTests.Services
{
    [Category("BettypeWith3rdProducts.UnitTests.Services FileServiceUnitTests")]
    public class FileServiceUnitTests
    {
        private RepositoryService repositoryService;
        private ApplicationConfigurationService appConfig;

        private void InitializeSubstitute()
        {
            Directory.SetCurrentDirectory(AppDomain.CurrentDomain.BaseDirectory);
            repositoryService = Substitute.For<RepositoryService>();
            appConfig = Substitute.For<ApplicationConfigurationService>();
        }

        [Test]
        public void ReadContentWhenDataIsNotReady_Awlays_ReturnRightContent()
        {
            // Arrange
            InitializeSubstitute();
            repositoryService.QueryLastDate().Returns(new DateTime(2017, 01, 01));
            SystemTime.Set(new DateTime(2017, 01, 03));
            var expected = TestLoader.DataLoader("ContentWhenDataIsNotReady-Expected.txt");

            // Act
            var service = new FileServiceImp(repositoryService, appConfig);
            var result = service.ReadContentWhenDataIsNotReady();

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }

        [Test]
        public void ReadContentWhenDataIsAvailable_ContentWithAttachment_ReturnRightContent()
        {
            // Arrange
            InitializeSubstitute();
            appConfig.NapReportUrl.Returns(new Uri("http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index"));
            var expected = TestLoader.DataLoader("ContentWithAttachment-expected.txt");
            var fileName = "Bettype_With_3rd_Products_Monthly_Winloss_For_2017_06_03.xlsx";

            // Act
            var service = new FileServiceImp(repositoryService, appConfig);
            var result = service.ReadContentWhenDataIsAvailable(fileName, "ContentWithAttachment.cshtml");

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }

        [Test]
        public void ReadContentWhenDataIsAvailable_ContentWithoutAttachment_ReturnRightContent()
        {
            // Arrange
            InitializeSubstitute();
            appConfig.NapReportUrl.Returns(new Uri("http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index"));
            var expected = TestLoader.DataLoader("ContentWithoutAttachment-expected.txt");
            var fileName = "Bettype_With_3rd_Products_Monthly_Winloss_For_2017_06_03.xlsx";

            // Act
            var service = new FileServiceImp(repositoryService, appConfig);
            var result = service.ReadContentWhenDataIsAvailable(fileName, "ContentWithoutAttachment.cshtml");

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }
    }
}