using System;
using System.Collections.Generic;
using System.IO;
using Fanex.UpdateExchangeRate.Business.Models;
using Fanex.UpdateExchangeRate.Business.Services;
using NSubstitute;
using NUnit.Framework;

namespace UpdateExchangeRate.UnitTests.Services
{
    [Category("UpdateExchangeRate.UnitTests.Services MailServiceUnitTests")]
    public class MailServiceUnitTests
    {
        [SetUp]
        public void Initial()
        {
            Directory.SetCurrentDirectory(AppDomain.CurrentDomain.BaseDirectory);
        }

        [Test]
        public void Execute_Always_Successully()
        {
            // Arrange
            var appConfigService = Substitute.For<ApplicationConfigurationService>();
            var fileService = Substitute.For<FileService>();
            var excelService = Substitute.For<ExcelService>();
            var emailContent = "any text";

            excelService.Export(Arg.Any<List<CurrencyRate>>()).Save().Returns(@"Templates\Template.xlsx");
            fileService.ReadContent(Arg.Any<string>(), Arg.Any<int>()).Returns(emailContent);
            appConfigService.Configurations.Returns(new AppConfig { NapReportUrl = new Uri("http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index") }); // DevSkim: ignore DS137138

            // Act
            var service = new MailServiceImp(appConfigService, fileService, excelService);
            service.Execute(new List<CurrencyRate>());

            // Assert
            excelService.Received().Export(Arg.Any<List<CurrencyRate>>()).Save();
            fileService.Received().ReadContent(Arg.Any<string>(), Arg.Any<int>());
        }
    }
}