using System;
using System.IO;
using Fanex.UpdateExchangeRate.Business.Models;
using Fanex.UpdateExchangeRate.Business.Services;
using NSubstitute;
using NUnit.Framework;

namespace UpdateExchangeRate.UnitTests.Services
{
    [Category("UpdateExchangeRate.UnitTests.Services FileServiceUnitTests")]
    public class FileServiceUnitTests
    {
        [SetUp]
        public void Initial()
        {
            Directory.SetCurrentDirectory(AppDomain.CurrentDomain.BaseDirectory);
        }

        [Test]
        public void ReadContent_Always_ReturnRightContent()
        {
            // Arrange
            var appConfig = Substitute.For<ApplicationConfigurationService>();
            appConfig.Configurations.Returns(new AppConfig { NapReportUrl = new Uri("http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index") }); // DevSkim: ignore DS137138
            var expected = File.ReadAllText(@"Templates\ContentWithAttachmentExpected.txt");

            // Act
            var service = new FileServiceImp(appConfig);
            var result = service.ReadContent("Exchange.xlsx", 20);

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }
    }
}