using OfficeOpenXml;
using System;
using System.Data;
using System.IO;

namespace Fanex.SBABICustomerPerformance.Business.Services
{
    public interface ExcelRawService
    {
        string ExportExcel(DataTable dataTable);
    }

    public class ExcelRawServiceImp : ExcelRawService
    {
        private ExcelPackage excelPackage;
        private readonly DateTimeServiceProvider dateService;

        public ExcelRawServiceImp(
            ExcelPackage excelPackage,
            DateTimeServiceProvider dateService)
        {
            this.excelPackage = excelPackage;
            this.dateService = dateService;
        }

        public string ExportExcel(DataTable dataTable)
        {
            if (dataTable.Rows.Count > 0)
            {
                excelPackage = new ExcelPackage(new FileInfo($"Templates/SBABICustomerPerformance.xlsx"));
                var template = excelPackage.Workbook.Worksheets["Data"];
                template.Cells["B5"].LoadFromDataTable(dataTable, true);

                RenderTitle(template);
                RenderData(dataTable, template);
            }
            else
            {
                excelPackage = new ExcelPackage(new FileInfo($"Templates/SBABICustomerPerformance-NoData.xlsx"));
            }

            return Save();
        }

        private void RenderData(DataTable dataTable, ExcelWorksheet template)
        {
            var startRowIndex = 6;
            var maxRowIndex = dataTable.Rows.Count + startRowIndex - 1;

            for (int rowIndex = startRowIndex; rowIndex <= maxRowIndex; rowIndex++)
            {
                template.Row(rowIndex).Height = 19.5;
            }

            for (int columnIndex = 2; columnIndex <= 10; columnIndex++)
            {
                template.Cells[startRowIndex, columnIndex, maxRowIndex, columnIndex].StyleID = template.Cells[startRowIndex, columnIndex].StyleID;
            }

            for (int columnIndex = 11; columnIndex <= dataTable.Columns.Count + 1; columnIndex++)
            {
                template.Cells[startRowIndex - 1, columnIndex, startRowIndex - 1, columnIndex].StyleID = template.Cells[startRowIndex - 1, 11].StyleID;
                template.Cells[startRowIndex, columnIndex, maxRowIndex, columnIndex].StyleID = template.Cells[startRowIndex, 11].StyleID;
            }
        }

        private string Save()
        {
            var date = dateService.DateTime.WinlostDate;
            var fileName = $"SBABICustomerPerformance {date:yyyyMMdd}.xlsx";

            var path = $@"{AppConfigService.Config.Path}\{date:yyyy}\{date:MM}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.Config.Password);

            return path;
        }

        private void RenderTitle(ExcelWorksheet template)
        {
            var now = DateTime.Now;
            var winlostDate = dateService.DateTime.WinlostDate;

            template.Cells["B2"].Value = $"SB Danger level ABI 50 customer performance - {winlostDate:yyyy/MM/dd}";
            template.Cells["B3"].Value = $"Generated by it on {now}";
        }
    }
}