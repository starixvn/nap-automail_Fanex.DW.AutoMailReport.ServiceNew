using System;
using System.Collections.Generic;
using System.IO;
using MaxLossMonitoring.Business.Models;
using MaxLossMonitoring.Business.Services;
using Newtonsoft.Json;
using NSubstitute;
using NUnit.Framework;

namespace MaxLossMonitoring.UnitTests.Services
{
    [Category("MaxLossMonitoring.UnitTests.Services FileServiceUnitTests")]
    public class FileServiceUnitTests
    {
        [SetUp]
        public void Initialize()
        {
            Directory.SetCurrentDirectory(AppDomain.CurrentDomain.BaseDirectory);
        }

        [Test]
        public void ReadContentWithAttachedFile_Awlays_ReturnRightContent()
        {
            // Arrange
            var appConfig = Substitute.For<ApplicationConfigurationService>();
            appConfig.Configurations.Returns(new AppConfig { NapReportURL = "http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index" }); /*DevSkim: ignore DS137138*/
            var data = JsonConvert.DeserializeObject<Tuple<List<MonitorList>, List<MonitorListRaw>>>(File.ReadAllText("Templates/ExpectedQueryMonitorListForEmail.json"));
            var expected = File.ReadAllText("Templates/ExpectedReadContentWithAttachedFile.txt");

            // Action
            var service = new FileServiceImp(appConfig);
            var result = service.ReadContentWithAttachedFile(data);

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }

        [Test]
        public void ReadContentWithoutAttachedFile_Awlays_ReturnRightContent()
        {
            // Arrange
            var appConfig = Substitute.For<ApplicationConfigurationService>();
            appConfig.Configurations.Returns(new AppConfig { NapReportURL = "http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index" }); /*DevSkim: ignore DS137138*/
            var data = JsonConvert.DeserializeObject<Tuple<List<MonitorList>, List<MonitorListRaw>>>(File.ReadAllText("Templates/ExpectedQueryMonitorListForEmail.json"));
            var expected = File.ReadAllText("Templates/ExpectedReadContentWithoutAttachedFile.txt");
            var fileName = "List_Of_SMA_Reaching_Allowable_Max_Loss_For_2018_03_08.xlsx";

            // Action
            var service = new FileServiceImp(appConfig);
            var result = service.ReadContentWithoutAttachedFile(fileName);

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }
    }
}