using OfficeOpenXml;
using System;
using System.Data;
using System.IO;
using System.Linq;

namespace Fanex.SoccerNonLive.Business.Services
{
    public interface ExcelRawService
    {
        string ExportExcel(DataTable dataSource);
    }

    public class ExcelRawServiceImp : ExcelRawService
    {
        private ExcelPackage excelPackage;
        private readonly DateTimeServiceProvider dateService;

        public ExcelRawServiceImp(
            ExcelPackage excelPackage,
            DateTimeServiceProvider dateService)
        {
            this.excelPackage = excelPackage;
            this.dateService = dateService;
        }

        public string ExportExcel(DataTable dataSource)
        {
            if (dataSource.Rows.Count > 1)
            {
                excelPackage = new ExcelPackage(new FileInfo($"Templates/SoccerNonLive.xlsx"));
                var template = excelPackage.Workbook.Worksheets["Soccer Non-Live"];
                var templateFormat = excelPackage.Workbook.Worksheets["Format"];
                template.Cells["B10"].LoadFromDataTable(dataSource, false);
                excelPackage.Workbook.Worksheets.Delete(templateFormat);

                RenderTitle(template);
                RenderData(dataSource, template, templateFormat);
            }
            else
            {
                excelPackage = new ExcelPackage(new FileInfo($"Templates/SoccerNonLive-NoData.xlsx"));
                var template = excelPackage.Workbook.Worksheets["Soccer Non-Live"];
                RenderTitle(template);
            }

            return Save();
        }

        private void RenderData(DataTable dataSource, ExcelWorksheet template, ExcelWorksheet templateFormat)
        {
            var startRowIndex = 10;
            var endLeagueRowIndex = startRowIndex - 1;
            var maxRowIndex = dataSource.Rows.Count + startRowIndex - 1;

            for (int rowIndex = startRowIndex; rowIndex <= maxRowIndex; rowIndex++)
            {
                template.Row(rowIndex).Height = 14.5;
            }

            for (int columnIndex = 2; columnIndex <= dataSource.Columns.Count + 1; columnIndex++)
            {
                template.Cells[startRowIndex, columnIndex, maxRowIndex, columnIndex].StyleID = template.Cells[startRowIndex, columnIndex].StyleID;
            }

            dataSource.AsEnumerable()
                .Where(s => s["MatchEvent"].ToString().Length > 0)
                .GroupBy(g => new
                {
                    LeagueName = g["LeagueName"].ToString()
                }).ToList().ForEach(league =>
                {
                    endLeagueRowIndex += league.Count() + 1;
                    for (int columnIndex = 2; columnIndex <= dataSource.Columns.Count + 1; columnIndex++)
                    {
                        template.Cells[endLeagueRowIndex, columnIndex].StyleID = templateFormat.Cells[4, columnIndex].StyleID;
                    }

                    template.Cells[endLeagueRowIndex - league.Count(), 2, endLeagueRowIndex - 1, 2].Merge = true;
                });

            for (int columnIndex = 2; columnIndex <= dataSource.Columns.Count + 1; columnIndex++)
            {
                template.Cells[maxRowIndex, columnIndex].StyleID = templateFormat.Cells[5, columnIndex].StyleID;
            }
        }

        private string Save()
        {
            var date = dateService.DateTime.ToDate;
            var fileName = $"Daily_Soccer_NonLive_Performance_By_League_&_Match_Report_For_{date:yyyyMMdd}.xlsx";

            var path = $@"{AppConfigService.Config.Path}\{date:yyyy}\{date:MM}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.Config.Password);

            return path;
        }

        private void RenderTitle(ExcelWorksheet template)
        {
            var now = DateTime.Now;
            var winlostDate = dateService.DateTime.ToDate;

            template.Cells["B2"].Value = $"Daily Soccer Non-Live Performance By League & Match Report For {winlostDate:dd MMM, yyyy}";
            template.Cells["B3"].Value = $"Generated by StarixIT on {now:dd MMM yyyy hh:mm:ss tt}";
        }
    }
}