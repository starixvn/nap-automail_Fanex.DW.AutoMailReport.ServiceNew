using System;
using System.IO;
using EventMarketOffer.Business.Models;
using EventMarketOffer.Business.Services;
using Fanex.Service.Core;
using NSubstitute;
using NUnit.Framework;

namespace EventMarketOffer.UnitTests.Services
{
    [Category("EventMarketOffer.UnitTests.Services FileServiceUnitTests")]
    public class FileServiceUnitTests
    {
        private RepositoryService repositoryService;
        private AppConfigurationService appConfig;

        [SetUp]
        public void Initialize()
        {
            Directory.SetCurrentDirectory(AppDomain.CurrentDomain.BaseDirectory);
            repositoryService = Substitute.For<RepositoryService>();
            appConfig = Substitute.For<AppConfigurationService>();
        }

        [Test]
        public void ReadContentWhenDataIsAvailable_Always_ReturnRightContent()
        {
            // Arrange
            var fileName = "FileName.xlsx";
            appConfig.Configurations.Returns(new AppConfig { NapReportUrl = new Uri("http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index") });
            var expected = File.ReadAllText(@"Templates\ReadContentWhenDataIsAvailable-Expected.txt");

            // Act
            var service = new FileServiceImp(repositoryService, appConfig);
            var result = service.ReadContentWhenDataIsAvailable(fileName);

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }

        [Test]
        public void ReadContentWhenDataIsNotReady_Always_ReturnRightContent()
        {
            // Arrange
            repositoryService.QueryLastDate().Returns(new DateTime(2017, 07, 01));
            var expected = File.ReadAllText(@"Templates\ReadContentWhenDataIsNotReady-Expected.txt");
            SystemTime.Set(new DateTime(2017, 07, 10));

            // Act
            var service = new FileServiceImp(repositoryService, appConfig);
            var result = service.ReadContentWhenDataIsNotReady();

            // Assert
            Assert.That(result, Is.EqualTo(expected));
        }
    }
}