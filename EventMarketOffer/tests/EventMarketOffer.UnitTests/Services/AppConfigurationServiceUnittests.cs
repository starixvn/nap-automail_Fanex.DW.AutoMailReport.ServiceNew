using System;
using System.IO;
using EventMarketOffer.Business.Models;
using EventMarketOffer.Business.Services;
using NUnit.CompareNetObjects;
using NUnit.Framework;

namespace EventMarketOffer.UnitTests.Services
{
    [Category("EventMarketOffer.UnitTests.Services AppConfigurationServiceUnittests")]
    public class AppConfigurationServiceUnittests
    {
        [SetUp]
        public void Initialize()
        {
            Directory.SetCurrentDirectory(AppDomain.CurrentDomain.BaseDirectory);
        }

        [Test]
        public void Configurations_Always_ReturnRightContent()
        {
            // Arrange
            var expected = new AppConfig
            {
                ExportDataDirectory = "\\\\10.18.200.120\\www\\Olympus\\Fanex.Excel\\EventMarketOffer",
                ExcelPasswordProtected = string.Empty,
                IsCheckEnoughData = false,
                IsManual = false,
                FunctionIdNodata = 90,
                NapReportUrl = new Uri("http://ha.nexdev.net:7303/Main/Misc/AutoGeneratedReport/Index"),
                Subject = "Automail report - Event Market Offered",
                Title = "Auto Generated Report Administrator",
                DateStart = new DateTime(2017, 07, 01),
                DateEnd = new DateTime(2017, 07, 30)
            };

            // Act
            var service = new AppConfigurationServiceImp();
            var result = service.Configurations;

            // Assert
            Assert.That(result, IsDeeplyEqual.To(expected));
        }
    }
}