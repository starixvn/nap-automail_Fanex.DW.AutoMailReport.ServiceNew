using OfficeOpenXml;
using System;
using System.Data;
using System.IO;

namespace Fanex.DHWL.Business.Services.HouseNetIncome
{
    public interface ExcelRawService
    {
        string Export(DataTable dailyRawData, string fileName, DateTime fromdate, DateTime todate);
    }

    public class ExcelRawServiceImp : ExcelRawService
    {
        private readonly DateTimeServiceProvider dateService;

        public ExcelRawServiceImp(DateTimeServiceProvider dateService)
        {
            this.dateService = dateService;
        }

        public string Export(DataTable dailyRawData, string fileName, DateTime fromdate, DateTime todate)
        {
            var templatePath = $"Templates/DHWL-RawData.xlsx";

            if (!File.Exists(templatePath))
            {
                throw new FileNotFoundException($"Template file not found: {templatePath}");
            }

            ExcelPackage excelPackage = null;
            try
            {
                excelPackage = new ExcelPackage(new FileInfo(templatePath));

                if (excelPackage.Workbook == null)
                {
                    throw new InvalidOperationException("Excel workbook is null");
                }

                var template = excelPackage.Workbook.Worksheets["DHWL-RawData"];

                if (template == null)
                {
                    throw new InvalidOperationException("Worksheet 'DHWL-RawData' not found in template");
                }

                template.Cells["B5"].LoadFromDataTable(dailyRawData, true);

                RenderTitle(template, fromdate, todate);
                RenderData(dailyRawData, template);

                return Save(excelPackage, fileName);
            }
            catch (Exception ex)
            {
                throw new InvalidOperationException($"Error in ExcelRawService.Export: {ex.Message}", ex);
            }
            finally
            {
                if (excelPackage != null)
                {
                    excelPackage.Dispose();
                }
            }
        }

        private void RenderData(DataTable dailyRawData, ExcelWorksheet template)
        {
            var startRowIndex = 6;
            var maxRowIndex = dailyRawData.Rows.Count + startRowIndex - 1;

            for (int rowIndex = startRowIndex; rowIndex <= maxRowIndex; rowIndex++)
            {
                template.Row(rowIndex).Height = 14.4;
            }

            for (int columnIndex = 2; columnIndex <= 10; columnIndex++)
            {
                template.Cells[startRowIndex, columnIndex, maxRowIndex, columnIndex].StyleID =
                    template.Cells[startRowIndex, columnIndex].StyleID;
                template.Column(columnIndex).AutoFit();
            }

            for (int columnIndex = 11; columnIndex <= dailyRawData.Columns.Count + 1; columnIndex++)
            {
                template.Cells[startRowIndex - 1, columnIndex, startRowIndex - 1, columnIndex].StyleID =
                    template.Cells[startRowIndex - 1, 11].StyleID;
                template.Cells[startRowIndex, columnIndex, maxRowIndex, columnIndex].StyleID =
                    template.Cells[startRowIndex, 11].StyleID;
                template.Column(columnIndex).AutoFit();
            }
        }

        private string Save(ExcelPackage excelPackage, string fileName)
        {
            var date = dateService.DateTime.ToDate;
            var filename = $"{fileName} - RAW House Income - {date:yyyyMMdd}.xlsx";

            var path = $@"{AppConfigService.Config.Path}\{date:yyyy}\{date:MM}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{filename}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.Config.Password);

            return path;
        }

        private void RenderTitle(ExcelWorksheet template, DateTime fromdate, DateTime todate)
        {
            var now = DateTime.Now;

            template.Cells["B2"].Value =
                $"RAW DATA - House Month-to-Date Net Income Report From {fromdate:yyyy-MM-dd} To {todate:yyyy-MM-dd}";
            template.Cells["B3"].Value = $"Generated by it on {now}";
        }
    }
}