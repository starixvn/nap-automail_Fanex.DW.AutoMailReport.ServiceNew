using Fanex.IBOPerformance.Service.Models;
using Fanex.Service.Core;
using OfficeOpenXml;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace Fanex.IBOPerformance.Service.Services
{
    public interface ExcelService
    {
        List<string> ExportExcel(List<DailyCreatedCustomerModel> createdCustomers, List<DailyPerformanceModel> performanceCustomer);
    }

    public class ExcelServiceImp : ExcelService
    {
        private ExcelPackage excelPackage;
        private readonly DateService dateService;

        public ExcelServiceImp(DateService dateService)
        {
            this.dateService = dateService;
        }

        private string ExportCreatedCustomer(List<DailyCreatedCustomerModel> data)
        {
            excelPackage = new ExcelPackage(new FileInfo("Templates/IBO-CreatedCustomer.xlsx"));
            var template = excelPackage.Workbook.Worksheets["Customer List"];
            template.Cells["B2"].Value = $"Daily Created IBO Customers Report on {dateService.GetYesterday():yyyy/MM/dd}";
            template.Cells["B3"].Value = $"Generated by StarixIT on {SystemTime.Now:yyyy/MM/dd hh:mm:ss tt}";

            var customers = RefineCreatedCustomer(data);
            template.Cells["B6"].LoadFromCollection(customers, false);

            const int startRowIndex = 6;
            const int startColIndex = 2;
            const int totalCol = 3;
            var maxRowIndex = data.Count + 5;
            for (int columnIndex = 0; columnIndex < totalCol; columnIndex++)
            {
                template.Cells[startRowIndex, startColIndex + columnIndex, maxRowIndex, startColIndex + columnIndex].StyleID = template.Cells[startRowIndex, startColIndex + columnIndex].StyleID;
            }

            if (customers.Count == 0)
            {
                template.Cells["B6:D6"].Value = "There is no data.";
                template.Cells["B6:D6"].Merge = true;
                template.Cells["B6:D6"].Style.HorizontalAlignment = OfficeOpenXml.Style.ExcelHorizontalAlignment.Center;
            }

            return SaveCreatedFile();
        }

        private static List<DailyCreatedCustomerModel> RefineCreatedCustomer(List<DailyCreatedCustomerModel> data)
        {
            var customers = new List<DailyCreatedCustomerModel>();
            var count = 1;
            data.OrderByDescending(o => o.CreateDate)
                .ToList()
                .ForEach(c =>
                {
                    customers.Add(new DailyCreatedCustomerModel
                    {
                        Counted = count,
                        CreateDate = c.CreateDate,
                        UserName = c.UserName
                    });

                    count++;
                });

            return customers;
        }

        private string SaveCreatedFile()
        {
            var yesterday = dateService.GetYesterday();
            var fileName = $"Daily_Created_IBO_Customers_Report_For_{yesterday:yyyyMMdd}.xlsx";
            var path = $@"{AppConfigService.AppConfig.Path}\{yesterday:yyyy}\{yesterday:MM}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.AppConfig.Password);

            return path;
        }

        private string ExportPerformance(List<DailyPerformanceModel> data)
        {
            excelPackage = new ExcelPackage(new FileInfo("Templates/IBO-CustomerPerformance.xlsx"));
            var template = excelPackage.Workbook.Worksheets["Customer Performance"];
            var totalSheet = excelPackage.Workbook.Worksheets["Total"];
            excelPackage.Workbook.Worksheets.Delete(totalSheet);
            var yesterday = dateService.GetYesterday();

            template.Cells["B2"].Value = $"Daily IBO Customer Performance Report on {yesterday:yyyy/MM/dd}";
            template.Cells["B3"].Value = $"Generated by StarixIT on {SystemTime.Now:yyyy/MM/dd hh:mm:ss tt}";
            template.Cells["E5"].Value = $"{yesterday.AddYears(-1):yyyy/MM/dd} - {yesterday:yyyy/MM/dd}";

            var customers = RefinePerformanceList(data);
            template.Cells["B7"].LoadFromCollection(customers, false);

            const int startRowIndex = 7;
            const int startColIndex = 2;
            const int totalCol = 7;
            var maxRowIndex = data.Count + 7;
            for (int columnIndex = 0; columnIndex < totalCol; columnIndex++)
            {
                template.Cells[startRowIndex, startColIndex + columnIndex, maxRowIndex, startColIndex + columnIndex].StyleID = template.Cells[startRowIndex, startColIndex + columnIndex].StyleID;
            }

            if (customers.Count == 1)
            {
                template.Cells["B7:H7"].Value = "There is no data.";
                template.Cells["B7:H7"].Merge = true;
                template.Cells["B7:H7"].Style.HorizontalAlignment = OfficeOpenXml.Style.ExcelHorizontalAlignment.Center;
            }
            else
            {
                for (int columnIndex = 0; columnIndex < totalCol; columnIndex++)
                {
                    template.Cells[maxRowIndex, startColIndex + columnIndex, maxRowIndex, startColIndex + columnIndex].StyleID = totalSheet.Cells[startRowIndex, startColIndex + columnIndex].StyleID;
                }

                template.Cells[maxRowIndex, 2, maxRowIndex, 3].Merge = true;
                template.Cells[maxRowIndex, 2, maxRowIndex, 3].Value = "Total";
            }

            return SavePerformanceFile();
        }

        private static List<DailyPerformanceModel> RefinePerformanceList(List<DailyPerformanceModel> data)
        {
            var customers = new List<DailyPerformanceModel>();
            var count = 1;
            data.ForEach(c =>
                {
                    customers.Add(new DailyPerformanceModel
                    {
                        Counted = count,
                        UserName = c.UserName,
                        YesterdayTurnover = c.YesterdayTurnover,
                        BetCount = c.BetCount,
                        Winloss = c.Winloss,
                        Turnover = c.Turnover
                    });

                    count++;
                });

            customers.Add(new DailyPerformanceModel
            {
                UserName = "Total",
                YesterdayTurnover = data.Sum(s => s.YesterdayTurnover),
                BetCount = data.Sum(s => s.BetCount),
                Winloss = data.Sum(s => s.Winloss),
                Turnover = data.Sum(s => s.Turnover)
            });

            return customers;
        }

        private string SavePerformanceFile()
        {
            var yesterday = dateService.GetYesterday();
            var fileName = $"Daily_IBO_Customer_Performance_Report_For_{yesterday:yyyyMMdd}.xlsx";
            var path = $@"{AppConfigService.AppConfig.Path}\{yesterday:yyyy}\{yesterday:MM}";
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }

            path = $@"{path}\{fileName}";
            excelPackage.SaveAs(new FileInfo(path), AppConfigService.AppConfig.Password);

            return path;
        }

        public List<string> ExportExcel(List<DailyCreatedCustomerModel> createdCustomers, List<DailyPerformanceModel> performanceCustomer)
        {
            var fileCreatedCustomer = ExportCreatedCustomer(createdCustomers);
            var filePerformanceCustomer = ExportPerformance(performanceCustomer);

            return new List<string>
            {
                fileCreatedCustomer,
                filePerformanceCustomer
            };
        }
    }
}